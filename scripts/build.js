#!/usr/bin/env node
'use strict';
// Build both editions from one source.
//   editions/lite/              generated lite plugin dir (committed; marketplace source)
//   dist/portfolio-copilot.plugin, dist/portfolio-copilot-lite.plugin   zip bundles
//   portfolio-copilot.plugin, portfolio-copilot-lite.plugin            copies at repo root (README links)
// `node scripts/build.js --check` exits 1 if editions/lite is out of date (used in CI/tests).

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT = path.join(__dirname, '..');
const SHARED = ['core', 'hooks', 'skills', 'agents', 'context', 'LICENSE', 'DISCLAIMER.md'];
const LITE_DIR = path.join(ROOT, 'editions', 'lite');

function walk(rel) {
  const abs = path.join(ROOT, rel);
  if (fs.statSync(abs).isFile()) return [rel];
  return fs.readdirSync(abs).sort().flatMap((n) => walk(path.join(rel, n)));
}

function manifest() {
  return JSON.parse(fs.readFileSync(path.join(ROOT, '.claude-plugin', 'plugin.json'), 'utf8'));
}

function liteFiles() {
  const full = manifest();
  const files = new Map();
  for (const rel of SHARED.flatMap(walk)) files.set(rel.split(path.sep).join('/'), fs.readFileSync(path.join(ROOT, rel)));
  const lite = {
    ...full,
    name: 'portfolio-copilot-lite',
    description: 'Analysis-and-drafting edition: reads Zerodha/Kotak Neo, audits GTTs against your policy, drafts GTT plans and baskets that you enter yourself. Cannot place orders. Not investment advice.',
  };
  files.set('.claude-plugin/plugin.json', Buffer.from(JSON.stringify(lite, null, 2) + '\n'));
  // Lite: the order gate denies every broker write.
  const hooks = fs.readFileSync(path.join(ROOT, 'hooks', 'hooks.json'), 'utf8');
  files.set('hooks/hooks.json', Buffer.from(hooks.replace(/order-gate\.js\\"/g, 'order-gate.js\\" --edition=lite')));
  files.set('README.md', Buffer.from(`# portfolio-copilot-lite\n\nGenerated by \`scripts/build.js\` from the repository root. Do not edit here.\n\nSame skills, policy engine and guardrails as portfolio-copilot, without any order execution: every GTT plan and basket is a draft you enter in Kite web yourself. See the [main README](../../README.md).\n`));
  return files;
}

function fullFiles() {
  const files = new Map();
  for (const rel of [...SHARED, '.claude-plugin/plugin.json', 'README.md'].flatMap(walk)) files.set(rel.split(path.sep).join('/'), fs.readFileSync(path.join(ROOT, rel)));
  return files;
}

// ---- minimal zip writer (deflate) ------------------------------------------------------

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  if (zlib.crc32) return zlib.crc32(buf);
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function zip(files) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  const DOS_TIME = 0;
  const DOS_DATE = (2026 - 1980) << 9 | 1 << 5 | 1; // fixed date: reproducible builds
  for (const [name, data] of [...files.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const nameBuf = Buffer.from(name);
    const comp = zlib.deflateRawSync(data, { level: 9 });
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6); local.writeUInt16LE(8, 8);
    local.writeUInt16LE(DOS_TIME, 10); local.writeUInt16LE(DOS_DATE, 12); local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(data.length, 22); local.writeUInt16LE(nameBuf.length, 26); local.writeUInt16LE(0, 28);
    locals.push(local, nameBuf, comp);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6); central.writeUInt16LE(0x0800, 8); central.writeUInt16LE(8, 10);
    central.writeUInt16LE(DOS_TIME, 12); central.writeUInt16LE(DOS_DATE, 14); central.writeUInt32LE(crc, 16); central.writeUInt32LE(comp.length, 20);
    central.writeUInt32LE(data.length, 24); central.writeUInt16LE(nameBuf.length, 28); central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);
    offset += 30 + nameBuf.length + comp.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.size, 8); end.writeUInt16LE(files.size, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}

// ---- edition directory sync -------------------------------------------------------------

function diffLite(files) {
  const problems = [];
  const existing = fs.existsSync(LITE_DIR) ? walkAbs(LITE_DIR).map((f) => path.relative(LITE_DIR, f).split(path.sep).join('/')) : [];
  for (const [rel, data] of files) {
    const p = path.join(LITE_DIR, rel);
    if (!fs.existsSync(p)) problems.push(`missing ${rel}`);
    else if (!normalize(fs.readFileSync(p)).equals(normalize(data))) problems.push(`stale ${rel}`);
  }
  for (const rel of existing) if (!files.has(rel)) problems.push(`extra ${rel}`);
  return problems;
}

function normalize(buf) {
  return Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n'));
}

function walkAbs(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walkAbs(path.join(dir, e.name)) : [path.join(dir, e.name)]));
}

function writeLite(files) {
  fs.rmSync(LITE_DIR, { recursive: true, force: true });
  for (const [rel, data] of files) {
    const p = path.join(LITE_DIR, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, data);
  }
}

function main() {
  const lite = liteFiles();
  if (process.argv.includes('--check')) {
    const problems = diffLite(lite);
    if (problems.length) {
      console.error(`editions/lite is out of date (run: node scripts/build.js):\n  ${problems.join('\n  ')}`);
      process.exit(1);
    }
    console.log('editions/lite is up to date');
    return;
  }
  writeLite(lite);
  const dist = path.join(ROOT, 'dist');
  fs.mkdirSync(dist, { recursive: true });
  const full = zip(fullFiles());
  const liteZip = zip(lite);
  fs.writeFileSync(path.join(dist, 'portfolio-copilot.plugin'), full);
  fs.writeFileSync(path.join(dist, 'portfolio-copilot-lite.plugin'), liteZip);
  fs.writeFileSync(path.join(ROOT, 'portfolio-copilot.plugin'), full);
  fs.writeFileSync(path.join(ROOT, 'portfolio-copilot-lite.plugin'), liteZip);
  console.log(`built v${manifest().version}: full ${fullFiles().size} files, lite ${lite.size} files`);
}

if (require.main === module) main();

module.exports = { liteFiles, fullFiles, diffLite, zip };
